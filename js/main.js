  var CMS_KEY = "prixna_cms_v1";
  function cmsLoad() {
    try { return JSON.parse(localStorage.getItem(CMS_KEY) || "{}"); }
    catch (e) { return {}; }
  }
  function cmsSave(ov) { localStorage.setItem(CMS_KEY, JSON.stringify(ov)); }
  (function cmsMerge() {
    try {
      var ov = cmsLoad();
      if (ov.config) { for (var k in ov.config) { if (ov.config[k] !== "" || k === "formEndpoint" || k === "analyticsId") C[k] = ov.config[k]; } }
      var D = window.PRIXNA_DATA || {};
      if (ov.products) D.products = ov.products;
      if (ov.trustFacts) D.trustFacts = ov.trustFacts;
      if (ov.testimonials) D.testimonials = ov.testimonials;
      if (ov.content && D.content) { for (var c in ov.content) { if (typeof D.content[c] !== "undefined") D.content[c] = ov.content[c]; } }
    } catch (e) {}
  })();
  function cmsEsc(s) {
    return String(s == null ? "" : s).replace(/[&<>"']/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c];
    });
  }
  /* Apply data-cms text hooks, trust-bar overrides and approved testimonials. */
  function hydrateCMS() {
    var D = window.PRIXNA_DATA || {};
    var ov = cmsLoad();
    var content = D.content || {};
    document.querySelectorAll("[data-cms]").forEach(function (el) {
      var key = el.getAttribute("data-cms");
      if (content[key] == null) return;
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") el.value = content[key];
      else el.textContent = content[key];
    });
    if (ov.trustFacts) {
      var bar = document.getElementById("trustbar-items");
      if (bar && D.trustFacts) {
        bar.innerHTML = D.trustFacts.map(function (t) {
          return '<div class="trust-item"><span class="t-ico">' + cmsEsc(t.icon) + "</span><div><b>" + cmsEsc(t.title) + "</b><span>" + cmsEsc(t.text) + "</span></div></div>";
        }).join("");
      }
    }
    var grid = document.getElementById("testimonial-grid") ||
      (function () { var ph = document.getElementById("tm-slot"); return ph ? ph.parentElement : null; })();
    var list = (D.testimonials || []).filter(function (t) { return t && t.approved; });
    if (grid && list.length && !grid.dataset.tmDone) {
      grid.dataset.tmDone = "1";
      var html = list.map(function (t) {
        var n = Math.max(1, Math.min(5, t.stars || 5));
        var stars = "★★★★★".slice(0, n) + "☆☆☆☆☆".slice(0, 5 - n);
        return '<article class="card quote-card rv vis"><div class="stars">' + stars + "</div><p>“" + cmsEsc(t.text) + "”</p>" +
          '<p class="small muted">— ' + cmsEsc(t.author || "Verified customer") + (t.source ? " · " + cmsEsc(t.source) : "") + "</p></article>";
      }).join("");
      var ph = grid.querySelector(".placeholder");
      if (ph) ph.insertAdjacentHTML("beforebegin", html);
      else grid.insertAdjacentHTML("beforeend", html);
    }
  }
